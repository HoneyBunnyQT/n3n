def esc(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def svg(width, height, title, desc, body):
    return """<svg xmlns="http://www.w3.org/2000/svg" \
viewBox="0 0 {w} {h}" width="{w}" height="{h}" \
role="img" aria-labelledby="title desc">
  <title id="title">{t}</title>
  <desc id="desc">{d}</desc>
  <!-- SPDX-License-Identifier: GPL-3.0-only -->
  <!-- SPDX-FileCopyrightText: Copyright Honey Bunny QT -->
  <!-- Generated by scripts/gen_doc_images.py: change it there -->{style}
{body}
</svg>
""".format(w=width, h=height, t=esc(title), d=esc(desc), style=STYLE,
           body="\n".join(body))


def text(x, y, s, cls="label", anchor="middle"):
    return ('  <text class="{}" x="{:g}" y="{:g}" text-anchor="{}">{}</text>'
            .format(cls, x, y, anchor, esc(s)))


def rect(x, y, w, h, cls, rx=0):
    return ('  <rect class="{}" x="{:g}" y="{:g}" width="{:g}" height="{:g}"'
            ' rx="{}"/>'.format(cls, x, y, w, h, rx))


def wire(x0, y0, x1, y1, extra=""):
    return '  <path class="wire" d="M {} {} L {} {}"{}/>'.format(
        x0, y0, x1, y1, extra)


# --- packet layouts: 32 bits a row, as in the RFCs ------------------------

BIT = 18            # px per bit
ROW = 34            # px per row of 4 bytes
LEFT = 44           # room for the byte offsets
TOP = 34            # room for the bit ruler


def lines_of(label):
    return label.split("\n")


def layout(fields, title, desc, first=0):
    """fields: (label, first byte, bytes, kind) with kind one of box, hi
    (what the picture is about), opt (only sometimes there) or open (goes
    on, the payload).  first: the byte offset of the first row."""
    end = max(start + (n or 4 - start % 4) for _, start, n, _ in fields)
    rows = (end - first + 3) // 4
    width = LEFT + 32 * BIT + 12
    height = TOP + rows * ROW + 10
    body = []

    # the ruler: bit numbers, and the bytes
    for b in range(32):
        body.append(text(LEFT + b * BIT + BIT / 2, TOP - 8, str(b % 10),
                         "small"))
    for row in range(rows):
        body.append(text(LEFT - 8, TOP + row * ROW + ROW / 2 + 4,
                         str(first + 4 * row), "small", "end"))

    for label, start, n, kind in fields:
        if not n:
            # open: to the end of its row
            n = 4 - (start % 4)
        stop = start + n
        segments = []           # (row, first byte in it, bytes in it)
        b = start
        while b < stop:
            row = (b - first) // 4
            row_end = first + 4 * (row + 1)
            take = min(stop, row_end) - b
            segments.append((row, (b - first) % 4, take))
            b += take
        # whole rows in a row of them make one block
        blocks = []
        for row, col, take in segments:
            last = blocks[-1] if blocks else None
            if (last and col == 0 and take == 4 and last[1] == 0
                    and last[3] == 4 and last[0] + last[2] == row):
                r0, c0, nrows, t0 = blocks[-1]
                blocks[-1] = (r0, c0, nrows + 1, t0)
            else:
                blocks.append((row, col, 1, take))
        biggest = max(range(len(blocks)),
                      key=lambda i: blocks[i][2] * blocks[i][3])
        for i, (row, col, nrows, take) in enumerate(blocks):
            x = LEFT + col * 8 * BIT
            y = TOP + row * ROW
            w = take * 8 * BIT
            h = nrows * ROW
            body.append(rect(x + 1, y + 1, w - 2, h - 2, kind, 3))
            if i == biggest:
                lines = lines_of(label)
                y0 = y + h / 2 - (len(lines) - 1) * 8 + 4
                for k, line in enumerate(lines):
                    body.append(text(x + w / 2, y0 + 16 * k, line,
                                     "label" if k == 0 else "small"))
            else:
                # the rest of a field that does not fit in its row
                name = lines_of(label)[0]
                body.append(text(x + w / 2, y + h / 2 + 4,
                                 name + " …" if i < biggest else "… " + name,
                                 "small"))
    return svg(width, height, title, desc, body)


