def pre_iv():
    """The 128-bit pre-IV: checksum XOR time stamp, and 32 random bits"""
    px = 6                      # px per bit, 128 bits across
    left, top, row, gap = 20, 34, 40, 24
    width = left + 128 * px + 20
    height = top + 2 * row + gap + 36
    body = []
    for b in (0, 32, 64, 96, 127):
        body.append(text(left + b * px + (px / 2 if b == 127 else 0), top - 10,
                         str(b), "small", "middle"))

    def cell(b0, bits, r, label, cls="box", tall=False, first="label"):
        x = left + b0 * px
        y = top + r * (row + gap)
        h = 2 * row + gap if tall else row
        body.append(rect(x + 1, y + 1, bits * px - 2, h - 2, cls, 3))
        lines = lines_of(label)
        y0 = y + h / 2 - (len(lines) - 1) * 7 + 4
        for k, line in enumerate(lines):
            body.append(text(x + bits * px / 2, y0 + 14 * k, line,
                             first if k == 0 else "small"))

    cell(0, 64, 0, "64-bit checksum of the whole packet", "hi")
    cell(64, 32, 0, "0x00")
    cell(0, 32, 1, "0x00")
    cell(32, 52, 1, "52-bit time stamp, µs", "hi")
    cell(84, 8, 1, "counter", first="small")
    cell(92, 4, 1, "F")
    cell(96, 32, 0, "32 pseudo-\nrandom bits", "box", tall=True)
    body.append(text(left + 48 * px, top + row + gap / 2 + 6, "XOR", "xor"))
    body.append(text(left + 64 * px, top + 2 * row + gap + 26,
                     "the two rows exclusive-ored, the random bits next to "
                     "them: then one SPECK block step makes the IV",
                     "small"))
    return svg(width, height, "The 128-bit pre-IV of header encryption",
               "The checksum, exclusive-ored with the time stamp, its counter "
               "and flags, next to 32 pseudo-random bits.", body)


PICTURES["header-encryption-preiv.svg"] = pre_iv()


def netns_lab():
    """The lab of the netns scenarios"""
    w, h = 720, 330
    body = []
    bar_y = 120
    body.append(rect(30, bar_y, 660, 30, "bar", 8))
    body.append(text(360, bar_y + 20, '"internet" 203.0.113.0/24', "title"))

    def node(cx, y, title, sub, cls="box"):
        body.append(rect(cx - 70, y, 140, 50, cls, 8))
        body.append(text(cx, y + 22, title, "title"))
        body.append(text(cx, y + 39, sub, "small"))

    # the federated supernodes, above the bar
    for cx, name, addr in ((140, "sn1", ".1:7654"), (320, "sn2", ".2:7654")):
        body.append(wire(cx, 80, cx, bar_y))
        node(cx, 30, name, "supernode " + addr)
    body.append(wire(210, 55, 250, 55, ' stroke-dasharray="4 3"'))
    body.append(text(230, 20, "federated", "small"))

    # the edges without NAT
    body.append(wire(560, 80, 560, bar_y))
    node(560, 30, "public edges", "at .101 and up", "opt")

    # the sites: a router with its NAT, the edge behind it
    for cx, site, wan, ip in ((200, "a", ".11", "10.99.0.1/24"),
                              (520, "b", ".12", "10.99.0.2/24")):
        body.append(rect(cx - 110, 175, 220, 140, "nat", 12))
        body.append(text(cx - 98, 192, "site " + site, "small", "start"))
        body.append(wire(cx, bar_y + 30, cx, 200))
        node(cx, 200, "router " + site, "NAT, wan " + wan)
        body.append(wire(cx, 250, cx, 260))
        node(cx, 260, "edge " + site, ip, "hi")
    return svg(w, h, "The lab of the netns scenarios",
               "Two federated supernodes and the routers of two sites on one "
               "bridge, the internet; behind each router, with its kind of "
               "NAT, an edge.", body)


PICTURES["netns-lab.svg"] = netns_lab()


